local config = {}

-- =====================================================================
-- ПОДКЛЮЧЕНИЕ К БАЗЕ ДАННЫХ МАГАЗИНА
-- (нужно, чтобы тянуть актуальный список товаров и писать логи)
-- =====================================================================

-- ССЫЛКА НА БАЗУ ДАННЫХ (без слеша / на конце)
-- В ГИТХАБЕ ОСТАВЛЯЕМ ПУСТЫМ! Заполняем только на компьютере в игре.
config.firebase_url = "заменить"

-- Секретный ключ базы данных Firebase
-- В ГИТХАБЕ ОСТАВЛЯЕМ ПУСТЫМ! Заполняем только на компьютере в игре.
config.db_secret = "заменить"

-- true = читать товары из Firebase /shop. false = только из локального файла.
config.use_database = true

-- Часовой пояс (смещение от UTC в часах). Например: 2 (Киев), 3 (Мск)
config.timezone = 3

-- =====================================================================
-- ПАРАМЕТРЫ АВТОКРАФТА
-- =====================================================================

-- Главный выключатель. false → программа стартует, но не заказывает крафты.
config.crafter_enabled = true

-- Интервал в секундах между проверками. 300 = 5 минут.
config.crafter_interval = 300

-- Порог запасов: заказывать крафт, если stock <= threshold.
-- 0 = только когда совсем закончился. 10 = пополнять при <=10.
config.crafter_threshold = 0

-- Сколько штук заказывать за один проход.
-- Можно переопределить для конкретного товара полем craft_amount в shop.items.
config.crafter_amount = 64

-- Максимум одновременно крафтящихся РАЗНЫХ предметов.
-- 2 = программа стартует 2 крафта, и как только один заканчивается — берёт следующий
-- из очереди дефицита. Можно менять в самой программе кнопками [-] / [+].
config.crafter_max_concurrent = 2

return config
